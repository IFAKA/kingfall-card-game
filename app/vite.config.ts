import { createHash } from 'node:crypto'
import { readdirSync } from 'node:fs'
import path from 'node:path'
import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'
import type { Plugin } from 'vite'

// The offline service worker (registered in src/pwa.ts): the build writes it with the list of every file the game needs, so after
// one visit it starts and plays without a connection. The list's hash names the cache, so each release replaces the last.
// Font subsets for other scripts and the old .woff copies are left to load (and be cached) only if a browser ever asks for them.
function serviceWorker(): Plugin {
  return {
    name: 'suitkeep-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const pub = readdirSync(path.resolve(import.meta.dirname, 'public')).filter(f => !/^(og\.png|robots\.txt|sitemap\.xml)$/.test(f))
      const files = [...Object.keys(bundle), ...pub].filter(f => !/(cyrillic|devanagari|greek|vietnamese|latin-ext)|\.woff$/.test(f)).sort()
      const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12)
      const precache = ['./', ...files.filter(f => f !== 'index.html').map(f => `./${f}`)]
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(version, precache) })
    },
  }
}

function swSource(version: string, precache: string[]) {
  return `// generated by vite.config.ts at build time
const CACHE = 'suitkeep-${version}'
const PRECACHE = ${JSON.stringify(precache)}
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('suitkeep-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()))
})
self.addEventListener('fetch', e => {
  const req = e.request
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return
  // the page itself: the newest from the network, the saved copy when offline
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(r => { const copy = r.clone(); caches.open(CACHE).then(c => c.put('./', copy)); return r }).catch(() => caches.match('./', { ignoreVary: true })))
    return
  }
  // everything else has a hashed or fixed name: the saved copy first, else fetch it and keep it
  // (ignoreVary: module scripts are fetched with an Origin header the precache requests didn't send)
  e.respondWith(caches.match(req, { ignoreVary: true }).then(hit => hit || fetch(req).then(r => { if (r.ok) { const copy = r.clone(); caches.open(CACHE).then(c => c.put(req, copy)) } return r })))
})
`
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), tailwindcss(), serviceWorker()],
  resolve: { alias: { '@': path.resolve(import.meta.dirname, './src') } },
  base: './', // relative asset paths: the built app works from any folder or host (itch.io, GitHub Pages, a zip)
})
